// Physical pages: on the console, 64 KiB frames a title maps into its own
// reservations, at more than one address if it likes. Here each allocation
// is a pagefile-backed section, its pages are 64 KiB slices of it, and a
// mapping is a view of consecutive slices in place of a host placeholder.

const PAGE: usize = 64 << 10;

struct Section {
    handle: HANDLE,
    pages: usize,
    /// Persistent full-section writable mapping, created lazily on first
    /// DirectStorage/physical write and unmapped only when the section drops.
    /// Avoids per-request `MapViewOfFile`/`UnmapViewOfFile` kernel TLB
    /// shootdowns across DirectStorage worker threads.
    backing: OnceLock<Option<usize>>,
    /// Per-page committed bitmap (1 bit per 64 KiB page) so `VirtualAlloc`
    /// (`MEM_COMMIT`) runs at most once per page on `SEC_RESERVE` sections.
    committed: Vec<AtomicU64>,
}

impl Section {
    fn new(handle: HANDLE, pages: usize) -> Self {
        let words = pages.div_ceil(64);
        let committed = (0..words).map(|_| AtomicU64::new(0)).collect();
        Self {
            handle,
            pages,
            backing: OnceLock::new(),
            committed,
        }
    }

    fn is_committed(&self, page: usize) -> bool {
        (self.committed[page / 64].load(Ordering::Acquire) & (1u64 << (page % 64))) != 0
    }

    fn mark_committed(&self, start: usize, end: usize) {
        for p in start..end {
            self.committed[p / 64].fetch_or(1u64 << (p % 64), Ordering::Release);
        }
    }

    /// Returns a writable pointer to `n` consecutive pages starting at
    /// `first_page` within this section's persistent backing view, lazily
    /// mapping the section once and committing any untouched pages.
    fn backing_slice(&self, first_page: usize, n: usize) -> Option<*mut u8> {
        use windows_sys::Win32::System::Memory::{FILE_MAP_WRITE, MapViewOfFile};
        let end = first_page.checked_add(n)?;
        if end > self.pages {
            return None;
        }
        let base = (*self.backing.get_or_init(|| {
            let total = self.pages.checked_mul(PAGE)?;
            // SAFETY: full-section private mapping of our own handle; unmapped
            // in `Section::drop` after all views and slices have dropped.
            let at = unsafe { MapViewOfFile(self.handle, FILE_MAP_WRITE, 0, 0, total) };
            (!at.Value.is_null()).then_some(at.Value as usize)
        }))?;
        if !on_wine() {
            // Coalesce uncommitted sub-runs so `VirtualAlloc(MEM_COMMIT)` runs
            // at most once per contiguous uncommitted range.
            let mut p = first_page;
            while p < end {
                while p < end && self.is_committed(p) {
                    p += 1;
                }
                let run_start = p;
                while p < end && !self.is_committed(p) {
                    p += 1;
                }
                if p > run_start {
                    let addr = base + run_start * PAGE;
                    let len = (p - run_start) * PAGE;
                    if !commit(addr, len) {
                        return None;
                    }
                    self.mark_committed(run_start, p);
                }
            }
        }
        Some((base + first_page * PAGE) as *mut u8)
    }
}

// SAFETY: a section handle and its immutable persistent backing base address
// may be shared across threads; callers write disjoint physical page ranges.
unsafe impl Send for Section {}
// SAFETY: as above.
unsafe impl Sync for Section {}

impl Drop for Section {
    fn drop(&mut self) {
        use windows_sys::Win32::System::Memory::UnmapViewOfFile;
        if let Some(Some(base)) = self.backing.get() {
            // SAFETY: our persistent full-section view; no `View::Cached`
            // holds an `Arc<Section>` anymore.
            unsafe {
                UnmapViewOfFile(MEMORY_MAPPED_VIEW_ADDRESS {
                    Value: *base as *mut c_void,
                });
            }
        }
        // SAFETY: our handle; title views keep the section alive on their own.
        unsafe { CloseHandle(self.handle) };
    }
}

/// Where a page lives, or what a view starts with: a section and a page
/// index in it.
#[derive(Clone)]
struct Slice {
    section: Arc<Section>,
    index: usize,
}

#[derive(Default)]
struct Physical {
    next_page: usize,
    pages: HashMap<usize, Slice>,
    /// Mapped views by address: their length and what they show.
    views: BTreeMap<usize, (usize, Slice)>,
}

static PHYSICAL: LazyLock<Mutex<Physical>> = LazyLock::new(|| {
    Mutex::new(Physical {
        // Page numbers are opaque to titles; 0 stays unused.
        next_page: 0x10_0000,
        ..Default::default()
    })
});

fn physical() -> MutexGuard<'static, Physical> {
    PHYSICAL.lock().unwrap_or_else(|e| e.into_inner())
}

/// Allocates up to `wanted` pages by asking `create` for sections of `chunk`
/// pages at a time: tries `wanted` in one section first, and on failure
/// halves the chunk size down to `min_chunk` so a host with tight commit
/// headroom still returns as many pages as it can.
fn alloc_sections<T>(
    wanted: usize,
    min_chunk: usize,
    mut create: impl FnMut(usize) -> Option<T>,
) -> Vec<(T, usize)> {
    let mut sections = Vec::new();
    let mut left = wanted;
    let mut chunk = wanted;
    let floor = min_chunk.max(1);
    while left > 0 {
        let ask = chunk.min(left);
        if let Some(section) = create(ask) {
            sections.push((section, ask));
            left -= ask;
        } else if ask > floor {
            chunk = (ask / 2).max(floor);
        } else {
            break;
        }
    }
    sections
}

/// `count` is in and out (pages wanted, pages given). Tries one section for
/// the whole request first, and on commit failure falls back to smaller
/// chunks (returning a partial count if the host hits its commit limit).
pub extern "system" fn XMemAllocatePhysicalPages(
    flags: u64,
    count: *mut usize,
    pages: *mut usize,
) -> BOOL {
    if count.is_null() || pages.is_null() {
        return 0;
    }
    // SAFETY: checked non-null.
    let n = unsafe { *count };
    if n.checked_mul(PAGE).filter(|&s| s > 0).is_none() {
        return 0;
    }
    // Under Wine a committed section is a sparse file, free until touched,
    // and committing a reserved one page by page costs a wineserver request
    // each that scans every range committed so far: commit it whole there.
    let section_flags = PAGE_READWRITE | if on_wine() { SEC_COMMIT } else { SEC_RESERVE };
    // Fall back down to 64 MiB (1024 x 64 KiB pages) chunks when the host
    // cannot satisfy a multi-GiB request in a single section.
    const MIN_CHUNK_PAGES: usize = (64 << 20) / PAGE;
    let mut last_error = None;
    let sections = alloc_sections(n, MIN_CHUNK_PAGES, |ask| {
        let size = ask.checked_mul(PAGE)?;
        // SAFETY: plain section creation.
        let handle = unsafe {
            CreateFileMappingW(
                INVALID_HANDLE_VALUE,
                std::ptr::null(),
                section_flags,
                (size as u64 >> 32) as u32,
                size as u32,
                std::ptr::null(),
            )
        };
        if handle.is_null() {
            last_error = Some(std::io::Error::last_os_error());
            None
        } else {
            Some(Arc::new(Section::new(handle, ask)))
        }
    });
    let got: usize = sections.iter().map(|&(_, c)| c).sum();
    if got == 0 {
        let error = last_error.unwrap_or_else(std::io::Error::last_os_error);
        tracing::warn!(n, %error, "XMemAllocatePhysicalPages failed");
        // SAFETY: checked non-null.
        unsafe { count.write(0) };
        return 0;
    }
    if got < n {
        tracing::warn!(
            wanted = n,
            got,
            chunks = sections.len(),
            flags = format_args!("{flags:#x}"),
            "XMemAllocatePhysicalPages: partial allocation"
        );
    } else if sections.len() > 1 {
        tracing::info!(
            n = got,
            chunks = sections.len(),
            flags = format_args!("{flags:#x}"),
            "XMemAllocatePhysicalPages: satisfied in chunks"
        );
    } else {
        tracing::debug!(
            n = got,
            flags = format_args!("{flags:#x}"),
            "XMemAllocatePhysicalPages"
        );
    }
    // SAFETY: checked non-null; report the actual count allocated.
    unsafe { count.write(got) };
    let mut physical = physical();
    let first = physical.next_page;
    physical.next_page += got * FRAMES;
    let mut out = 0usize;
    for (section, chunk_pages) in sections {
        for index in 0..chunk_pages {
            let slice = Slice {
                section: section.clone(),
                index,
            };
            let number = first + out * FRAMES;
            physical.pages.insert(number, slice);
            // SAFETY: the title passes room for `n >= got` page numbers.
            unsafe { pages.add(out).write(number) };
            out += 1;
        }
    }
    1
}

/// Page numbers count 4 KiB frames, so a 64 KiB page's is a multiple of
/// 16: Grand Theft Auto VI keeps them as 21-bit `number >> 4` and rebuilds
/// them with `<< 4` (128 GiB of pages at most).
const FRAMES: usize = PAGE >> 12;

/// Pages still mapped stay readable through their views until unmapped.
pub extern "system" fn XMemFreePhysicalPages(n: usize, pages: *const usize) -> BOOL {
    if pages.is_null() {
        return 0;
    }
    let mut physical = physical();
    for i in 0..n {
        // SAFETY: the title passes `n` page numbers.
        physical.pages.remove(&unsafe { *pages.add(i) });
    }
    1
}

/// A writable view onto consecutive slices of one section. Uses the section's
/// persistent lazily-mapped backing view to avoid per-write kernel TLB
/// shootdowns, falling back to a transient mapping if full-section VA
/// reservation failed.
enum View {
    Cached {
        _section: Arc<Section>,
        ptr: *mut u8,
        len: usize,
    },
    Transient {
        at: MEMORY_MAPPED_VIEW_ADDRESS,
        len: usize,
    },
}

impl View {
    /// Maps `n` slices from `slice` on.
    fn map(slice: &Slice, n: usize) -> Option<View> {
        use windows_sys::Win32::System::Memory::{FILE_MAP_WRITE, MapViewOfFile};
        let len = n.checked_mul(PAGE)?;
        if let Some(ptr) = slice.section.backing_slice(slice.index, n) {
            return Some(View::Cached {
                _section: slice.section.clone(),
                ptr,
                len,
            });
        }
        let offset = (slice.index * PAGE) as u64;
        // SAFETY: slices of a section we own; the view is ours until dropped.
        let at = unsafe {
            MapViewOfFile(
                slice.section.handle,
                FILE_MAP_WRITE,
                (offset >> 32) as u32,
                offset as u32,
                len,
            )
        };
        if at.Value.is_null() {
            return None;
        }
        let view = View::Transient { at, len };
        commit(at.Value as usize, len).then_some(view)
    }

    fn bytes(&mut self) -> &mut [u8] {
        match self {
            View::Cached { ptr, len, .. } => {
                // SAFETY: `_section` keeps the persistent backing view alive and
                // `backing_slice` committed all `len` bytes.
                unsafe { std::slice::from_raw_parts_mut(*ptr, *len) }
            }
            View::Transient { at, len } => {
                // SAFETY: the view holds `len` committed read-write bytes, ours
                // alone while `self` lives.
                unsafe { std::slice::from_raw_parts_mut(at.Value.cast(), *len) }
            }
        }
    }
}

impl Drop for View {
    fn drop(&mut self) {
        if let View::Transient { at, .. } = self {
            use windows_sys::Win32::System::Memory::UnmapViewOfFile;
            // SAFETY: our transient view.
            unsafe { UnmapViewOfFile(*at) };
        }
    }
}

/// The pages behind bytes `[offset, offset + len)` of `pages` (64 KiB
/// each), as runs of consecutive slices of one section: each run's first
/// slice and its length in pages. One look at the page table, which the
/// title's own mapping calls share with every DirectStorage worker. `None`
/// if a page is unknown or `pages` ends early.
fn runs(pages: &[usize], offset: usize, len: usize) -> Option<Vec<(Slice, usize)>> {
    let end = offset.checked_add(len)?;
    let pages = pages.get(offset / PAGE..end.div_ceil(PAGE))?;
    let physical = physical();
    let mut runs: Vec<(Slice, usize)> = Vec::new();
    for page in pages {
        let slice = physical.pages.get(page)?;
        match runs.last_mut() {
            Some((first, n))
                if Arc::ptr_eq(&first.section, &slice.section)
                    && slice.index == first.index + *n =>
            {
                *n += 1;
            }
            _ => runs.push((slice.clone(), 1)),
        }
    }
    Some(runs)
}

/// Copies `data` into physical pages, from `offset` bytes into the first,
/// whether or not they are mapped anywhere (DirectStorage destinations).
/// One view per run of consecutive pages, not one per page: each view
/// costs a map, a commit and an unmap (which flushes every core's TLB).
/// False if a page is unknown or the host fails.
pub(crate) fn write_physical(pages: &[usize], offset: usize, data: &[u8]) -> bool {
    let Ok(ok) = write_physical_with::<std::convert::Infallible>(pages, offset, data.len(), |at, dst| {
        dst.copy_from_slice(&data[at..at + dst.len()]);
        Ok(())
    });
    ok
}

/// Maps each run of consecutive physical pages behind `[offset, offset + len)`
/// once and invokes `fill(byte_offset, run_bytes)` directly on the mapped view.
/// Avoids intermediate multi-MiB staging allocations and double copies when
/// DirectStorage writes raw data into non-consecutive physical pages.
pub(crate) fn write_physical_with<E>(
    pages: &[usize],
    offset: usize,
    len: usize,
    mut fill: impl FnMut(usize, &mut [u8]) -> Result<(), E>,
) -> Result<bool, E> {
    let Some(runs) = runs(pages, offset, len) else {
        return Ok(false);
    };
    let (mut within, mut done) = (offset % PAGE, 0);
    for (slice, n) in &runs {
        let Some(mut view) = View::map(slice, *n) else {
            return Ok(false);
        };
        let k = (n * PAGE - within).min(len - done);
        fill(done, &mut view.bytes()[within..within + k])?;
        (within, done) = (0, done + k);
    }
    victory_gpu::physical_memory_written();
    Ok(true)
}

/// Bytes `[offset, offset + len)` of physical pages, writable in place
/// until dropped: DirectStorage decodes into it instead of a buffer it
/// would then copy.
pub(crate) struct PageWindow {
    view: View,
    within: usize,
    len: usize,
}

impl Drop for PageWindow {
    fn drop(&mut self) {
        victory_gpu::physical_memory_written();
    }
}

impl PageWindow {
    pub(crate) fn bytes(&mut self) -> &mut [u8] {
        let (within, len) = (self.within, self.len);
        &mut self.view.bytes()[within..within + len]
    }
}

/// A window on bytes `[offset, offset + len)` of `pages` when they are
/// consecutive pages of one allocation (how titles usually hand them out);
/// `None` otherwise (pages of several allocations, out of order, or
/// unknown, or a host failure), which `write_physical` then handles or
/// reports.
pub(crate) fn page_window(pages: &[usize], offset: usize, len: usize) -> Option<PageWindow> {
    let runs = runs(pages, offset, len)?;
    let [(slice, n)] = runs.as_slice() else {
        return None;
    };
    Some(PageWindow {
        view: View::map(slice, *n)?,
        within: offset % PAGE,
        len,
    })
}

/// Maps `n` pages at `address`, in place of what is mapped there; null
/// `pages` unmaps. Returns `address`, or null if a page or the host fails.
pub extern "system" fn XMemMapPhysicalPages(
    address: *mut c_void,
    n: usize,
    pages: *const usize,
) -> *mut c_void {
    let base = address as usize;
    let mut physical = physical();
    unmap(&mut physical, base, n * PAGE);
    if pages.is_null() {
        return address;
    }
    // SAFETY: the title passes `n` page numbers.
    let pages = unsafe { std::slice::from_raw_parts(pages, n) };
    let mut i = 0;
    while i < n {
        let Some(first) = physical.pages.get(&pages[i]).cloned() else {
            tracing::warn!(page = pages[i], "XMemMapPhysicalPages: unknown page");
            return std::ptr::null_mut();
        };
        // One view per run of consecutive slices of one section.
        let run = 1 + pages[i + 1..]
            .iter()
            .zip(1..)
            .take_while(|&(page, k)| {
                physical.pages.get(page).is_some_and(|s| {
                    Arc::ptr_eq(&s.section, &first.section) && s.index == first.index + k
                })
            })
            .count();
        if !map(&mut physical, base + i * PAGE, run * PAGE, first) {
            return std::ptr::null_mut();
        }
        i += run;
    }
    address
}

/// One page at each address; null `pages`, or a page number 0, unmaps
/// (Grand Theft Auto VI passes 0 for addresses to clear).
pub extern "system" fn XMemMapPhysicalPagesScatter(
    addresses: *const *mut c_void,
    n: usize,
    pages: *const usize,
) -> BOOL {
    if addresses.is_null() {
        return 0;
    }
    for i in 0..n {
        // SAFETY: the title passes `n` addresses and, unless null, `n` pages.
        let (address, page) = unsafe {
            (
                *addresses.add(i),
                if pages.is_null() || *pages.add(i) == 0 {
                    std::ptr::null()
                } else {
                    pages.add(i)
                },
            )
        };
        if XMemMapPhysicalPages(address, 1, page).is_null() {
            return 0;
        }
    }
    1
}

/// Maps the physical pages shown at `[from, from + len)` at `to` as well,
/// in place of what `to` shows; `from` 0 unmaps. The GPU's page-mapping
/// copies (`victory_gpu`, queue `CopyPageMappingsBatchX`): Grand Theft Auto
/// VI maps pages into a pool view, then has the GPU map them into its tiled
/// heap. Page by page; false if a source page is not mapped physical memory.
pub fn map_alias(to: u64, from: u64, len: u64) -> bool {
    let (to, from, len) = (to as usize, from as usize, len as usize);
    let mut physical = physical();
    unmap(&mut physical, to, len);
    for k in (0..len).step_by(PAGE) {
        if from == 0 {
            break;
        }
        let at = from + k;
        let Some(slice) = physical
            .views
            .range(..=at)
            .next_back()
            .filter(|(base, (size, _))| at < *base + size)
            .map(|(base, (_, s))| Slice {
                index: s.index + (at - base) / PAGE,
                section: s.section.clone(),
            })
        else {
            return false;
        };
        if !map(&mut physical, to + k, PAGE, slice) {
            return false;
        }
    }
    true
}

/// Win32 `MEM_COALESCE_PLACEHOLDERS` flag for `VirtualFree` (not exported by
/// `windows-sys` 0.61).
const MEM_COALESCE_PLACEHOLDERS: u32 = 0x0000_0001;

/// Maps `slice` and the slices after it over `[base, base + len)`, even when
/// `[base, base + len)` spans multiple adjacent placeholders (such as split
/// regions left by earlier partial unmaps or neighboring placeholder
/// allocations).
fn map(physical: &mut Physical, base: usize, len: usize, slice: Slice) -> bool {
    if len == 0 {
        return true;
    }
    // Fast path: coalesce adjacent split placeholders inside `[base, base + len)`
    // when they came from the same reservation so a single `MapViewOfFile3` can
    // replace them (fails harmlessly when already one placeholder or spanning
    // separate reservations).
    // SAFETY: only operates on placeholder regions covering `[base, base + len)`.
    unsafe {
        VirtualFree(
            base as *mut c_void,
            len,
            MEM_RELEASE | MEM_COALESCE_PLACEHOLDERS,
        );
    }
    let end = base + len;
    let mut cur = base;
    while cur < end {
        // SAFETY: `MEMORY_BASIC_INFORMATION` is a plain Win32 POD struct.
        let mut mbi: MEMORY_BASIC_INFORMATION = unsafe { std::mem::zeroed() };
        // SAFETY: `mbi` is valid and sized to `MEMORY_BASIC_INFORMATION`.
        let queried = unsafe {
            VirtualQueryEx(
                GetCurrentProcess(),
                cur as *const c_void,
                &mut mbi,
                size_of::<MEMORY_BASIC_INFORMATION>(),
            )
        };
        let chunk = if queried != 0 && mbi.RegionSize > 0 {
            let region_end = (mbi.BaseAddress as usize).saturating_add(mbi.RegionSize);
            let avail = region_end.saturating_sub(cur);
            if avail >= PAGE {
                (avail & !(PAGE - 1)).min(end - cur)
            } else {
                end - cur
            }
        } else {
            end - cur
        };
        let sub_slice = Slice {
            index: slice.index + (cur - base) / PAGE,
            section: slice.section.clone(),
        };
        if !map_single(physical, cur, chunk, sub_slice) {
            if cur > base {
                unmap(physical, base, cur - base);
            }
            return false;
        }
        cur += chunk;
    }
    true
}

/// Maps `slice` and the slices after it over `[base, base + len)`, which
/// lies within a single host placeholder.
fn map_single(physical: &mut Physical, base: usize, len: usize, slice: Slice) -> bool {
    // SAFETY: splits the placeholder around the range (failing harmlessly
    // when the range is the whole placeholder), then maps the section
    // there; both act only on placeholders.
    let view = unsafe {
        VirtualFree(
            base as *mut c_void,
            len,
            MEM_RELEASE | MEM_PRESERVE_PLACEHOLDER,
        );
        MapViewOfFile3(
            slice.section.handle,
            GetCurrentProcess(),
            base as *const c_void,
            (slice.index * PAGE) as u64,
            len,
            MEM_REPLACE_PLACEHOLDER,
            PAGE_READWRITE,
            std::ptr::null_mut(),
            0,
        )
    };
    if view.Value as usize != base {
        tracing::warn!(
            address = format_args!("{base:#x}"),
            len,
            error = %std::io::Error::last_os_error(),
            "mapping physical pages failed (not a placeholder?)"
        );
        return false;
    }
    if !commit(base, len) {
        // SAFETY: the view just mapped, back to a placeholder.
        unsafe { UnmapViewOfFile2(GetCurrentProcess(), view, MEM_PRESERVE_PLACEHOLDER) };
        return false;
    }
    // New contents, read-write: the GPU side's copies no longer guard it.
    victory_gpu::title_memory_remapped(base, len);
    physical.views.insert(base, (len, slice));
    true
}

/// Commits the section pages a view shows (once per page, whichever view).
fn commit(base: usize, len: usize) -> bool {
    if on_wine() {
        return true; // sections are committed whole there
    }
    // SAFETY: `[base, base + len)` is a view of a reserved section.
    if !unsafe { VirtualAlloc(base as *const c_void, len, MEM_COMMIT, PAGE_READWRITE) }.is_null() {
        return true;
    }
    let error = std::io::Error::last_os_error();
    if error.raw_os_error() == Some(ERROR_COMMITMENT_LIMIT as i32) {
        let mut info = PERFORMANCE_INFORMATION {
            cb: size_of::<PERFORMANCE_INFORMATION>() as u32,
            ..Default::default()
        };
        // SAFETY: the buffer and size describe a writable PERFORMANCE_INFORMATION.
        let queried = unsafe { K32GetPerformanceInfo(&mut info, info.cb) } != 0;
        victory_loader::log_crash(&commit_limit_message(len, &error, queried.then_some(&info)));
    } else {
        tracing::warn!(len, %error, "committing physical pages failed");
    }
    false
}

fn commit_limit_message(
    len: usize,
    error: &std::io::Error,
    info: Option<&PERFORMANCE_INFORMATION>,
) -> String {
    let mut message = format!(
        "VIctory: Windows commit limit reached while committing {len} bytes of physical pages: {error}.\n"
    );
    if let Some(info) = info {
        use std::fmt::Write;

        let committed = info.CommitTotal * info.PageSize / MIB;
        let limit = info.CommitLimit * info.PageSize / MIB;
        let _ = writeln!(
            message,
            "System commit: {committed} MiB of {limit} MiB in use."
        );
    }
    message.push_str(
        "Close other applications or increase the Windows paging file size, then retry.\n",
    );
    message
}

/// Returns `[base, base + len)` to placeholders; views reaching past it
/// are mapped again outside it.
fn unmap(physical: &mut Physical, base: usize, len: usize) {
    // No bytes: no view to return. The search below would still find the
    // view holding `base` and cut it in two there, and its range of views
    // starting inside would run backwards (which `BTreeMap` panics on).
    if len == 0 {
        return;
    }
    let end = base + len;
    // Views do not overlap: the one holding `base`, then those starting
    // inside (the GPU's page mappings make one view per page).
    let first = physical
        .views
        .range(..=base)
        .next_back()
        .filter(|(at, (size, _))| *at + size > base)
        .map(|(at, _)| *at);
    let hit: Vec<usize> = first
        .into_iter()
        .chain(physical.views.range(base + 1..end).map(|(at, _)| *at))
        .collect();
    for at in hit {
        let Some((size, slice)) = physical.views.remove(&at) else {
            continue;
        };
        victory_gpu::title_memory_remapped(at, size);
        // SAFETY: a view we mapped; it becomes a placeholder again.
        unsafe {
            UnmapViewOfFile2(
                GetCurrentProcess(),
                MEMORY_MAPPED_VIEW_ADDRESS {
                    Value: at as *mut c_void,
                },
                MEM_PRESERVE_PLACEHOLDER,
            )
        };
        if at < base {
            map(physical, at, base - at, slice.clone());
        }
        if at + size > end {
            let index = slice.index + (end - at) / PAGE;
            map(physical, end, at + size - end, Slice { index, ..slice });
        }
    }
}

/// The oldest layout we know; newer titles pass other flag values (Minecraft
/// 0x20000001) and read the same leading fields.
#[repr(C)]
#[derive(Debug, Default)]
pub struct WorkingSet {
    pub title_limit: usize,
    pub title_used: usize,
    pub tools_limit: usize,
    pub tools_used: usize,
    pub stack_used: u32,
    pub physical_pages: u32,
    pub gpu_optimal_limit: usize,
    pub gpu_optimal_used: usize,
    pub tools_gpu_optimal_limit: usize,
    pub tools_gpu_optimal_used: usize,
    pub kernel_pool_used: u32,
    pub kernel_pool_limit: u32,
}

/// The title's budget and our process's commit as what it uses. No tools
/// memory: a retail console.
// shortcut: all fields are filled whatever the flags ask for, and use is
// not split by bandwidth class (GPU-optimal use reads 0); track
// allocations per class if a title budgets from that field.
pub extern "system" fn XMemGetWorkingSetStatistics(_which: u32, out: *mut WorkingSet) -> BOOL {
    if out.is_null() {
        return 0;
    }
    let mut counters = PROCESS_MEMORY_COUNTERS {
        cb: size_of::<PROCESS_MEMORY_COUNTERS>() as u32,
        ..Default::default()
    };
    // SAFETY: our own process and a sized structure.
    unsafe { K32GetProcessMemoryInfo(GetCurrentProcess(), &mut counters, counters.cb) };
    let (gpu_optimal, standard) = victory_gpu::console::current().title_memory();
    let stats = WorkingSet {
        title_limit: gpu_optimal + standard - TRANSFERRED.load(Ordering::Relaxed),
        title_used: counters.PagefileUsage,
        gpu_optimal_limit: gpu_optimal,
        ..Default::default()
    };
    // SAFETY: checked non-null; the title passes room for the structure.
    unsafe { out.write(stats) };
    1
}

/// Hands title memory (standard, in 2 MiB pages) to the system. The other
/// transfers involve tools memory, which a retail console has none of.
pub extern "system" fn XMemTransferMemory(kind: u32, size: usize) -> BOOL {
    const TITLE_TO_SYSTEM: u32 = 0;
    tracing::info!(kind, size, "XMemTransferMemory");
    if size == 0 {
        return 1;
    }
    let Some(size) = size.checked_next_multiple_of(2 * MIB) else {
        return 0;
    };
    let standard = victory_gpu::console::current().title_memory().1;
    let moved = kind == TITLE_TO_SYSTEM
        && TRANSFERRED
            .fetch_update(Ordering::Relaxed, Ordering::Relaxed, |t| {
                t.checked_add(size).filter(|&t| t <= standard)
            })
            .is_ok();
    moved.into()
}

